def load_dataset(json_path: Path, limit: Optional[int]) -> List[Dict[str, Any]]:
    if not json_path.exists():
        raise FileNotFoundError(f"Dataset JSON not found: {json_path}")

    with json_path.open("r", encoding="utf-8") as dataset_file:
        data = json.load(dataset_file)

    if not isinstance(data, list):
        raise ValueError("Dataset JSON must contain a list of samples.")

    if limit is not None:
        data = data[:limit]
    return data


def extract_prompt(conversations: List[Dict[str, str]]) -> str:
    for turn in conversations:
        if turn.get("from") == "human":
            return turn.get("value", "").replace("<image>", "").strip()
    return ""


def extract_ground_truth(conversations: List[Dict[str, str]]) -> str:
    for turn in conversations:
        if turn.get("from") == "gpt":
            return turn.get("value", "").strip()
    return ""


def resolve_image_path(image_value: str, images_dir: Path) -> Optional[Path]:
    if not image_value:
        return None
    candidate = images_dir / image_value
    if candidate.exists():
        return candidate
    if candidate.suffix:
        return None
    for ext in (".jpg", ".png", ".jpeg"):
        alt = candidate.with_suffix(ext)
        if alt.exists():
            return alt
    return None


def evaluate_dataset(config: EvaluationConfig) -> EvaluationResults:
    dataset = load_dataset(config.dataset_json, config.limit)
    total_samples = len(dataset)
    images_dir = config.images_dir
    device_map = config.resolved_device_map()
    train_set_mode = "train" in config.dataset_json.name.lower() or 'val' in config.dataset_json.name.lower()
    gt_csv_path = config.ground_truth_csv or (COMBINED_CSV_PATH_TRAIN if train_set_mode else COMBINED_CSV_PATH_TEST)

    print(f"Loading Qwen3-VL model '{config.gaze_model_id}' with device map '{device_map}'...")
    qwen_processor, qwen_model = load_qwen3vl_model(config.gaze_model_id, device_map=device_map)

    if config.use_gpt_gaze_targets:
        print("Using GPT-extracted gaze targets (gpt_gaze_target and gpt_person_description fields)")
    else:
        print("Using parsed ground truth text for gaze targets")

    gt_candidates: List[Path] = [gt_csv_path]
    for extra_path in (
        COMBINED_CSV_PATH_TRAIN,
        COMBINED_CSV_PATH_TEST,
        Path("gazefollow/data/train_annotations_release.csv"),
        Path("gazefollow/data/test_annotations_release.csv"),
    ):
        if extra_path not in gt_candidates:
            gt_candidates.append(extra_path)
    gt_caches: List[Dict[str, Dict[str, str]]] = []
    for candidate in gt_candidates:
        cache = load_combined_description_cache(candidate)
        if cache:
            gt_caches.append(cache)
    in_out_lookup = load_in_out_lookup(config.in_out_labels_csv) if config.in_out_labels_csv else None
    if in_out_lookup is not None:
        print(f"Loaded in/out labels from {config.in_out_labels_csv} ({len(in_out_lookup)} entries)")
    missing_in_out: Set[str] = set()
    skipped_in_out_minus_one: Set[str] = set()
    in_out_counts = {0: 0, 1: 0}
    config.output_dir.mkdir(parents=True, exist_ok=True)

    sample_records: List[Dict[str, Any]] = []
    person_records: List[PersonLevelRecord] = []
    failed_samples: List[FailureRecord] = []
    dataset_gt_updates: List[DatasetUpdateRecord] = []
    dataset_updated = False
    already_processed = 0

    if config.resume_from:
        resume_path = config.resume_from
        if not resume_path.exists():
            raise FileNotFoundError(f"Resume checkpoint not found: {resume_path}")
        with resume_path.open("r", encoding="utf-8") as resume_file:
            resume_payload = json.load(resume_file)
        sample_records = resume_payload.get("sample_records", [])
        person_records = resume_payload.get("person_records", [])
        failed_samples = resume_payload.get("failed_samples", [])
        dataset_gt_updates = resume_payload.get("dataset_gt_updates", [])
        dataset_updated = bool(resume_payload.get("dataset_updated", dataset_gt_updates))
        already_processed = int(
            resume_payload.get("processed_samples", len(sample_records) + len(failed_samples))
        )
        already_processed = max(already_processed, len(sample_records) + len(failed_samples))
        start_index = min(already_processed, len(dataset))
        if start_index:
            dataset = dataset[start_index:]
            print(f"Resuming from {resume_path} ({already_processed} samples already processed)")
        total_samples = max(total_samples, already_processed)

    gaze_l2_errors: List[float] = []
    gaze_normalized_l2_errors: List[float] = []
    gaze_angular_errors: List[float] = []
    gaze_ious: List[float] = []
    gaze_modified_l2_errors: List[float] = []

    samples_with_ground_truth = 0
    samples_with_person_descriptions = 0
    samples_with_detections = 0
    total_person_descriptions = 0
    persons_with_detections = 0

    processed_offset = max(already_processed, len(sample_records) + len(failed_samples)) - (
        len(sample_records) + len(failed_samples)
    )

    def processed_count() -> int:
        return processed_offset + len(sample_records) + len(failed_samples)

    def restore_resume_state() -> None:
        nonlocal samples_with_ground_truth
        nonlocal samples_with_person_descriptions
        nonlocal samples_with_detections
        nonlocal total_person_descriptions
        nonlocal persons_with_detections

        if not sample_records and not failed_samples and not person_records:
            return

        samples_with_ground_truth = len(sample_records) + sum(
            1 for failure in failed_samples if failure.get("reason") != "Missing ground truth text"
        )
        samples_with_person_descriptions = len(sample_records)
        samples_with_detections = sum(
            1
            for record in sample_records
            if any(det.get("gaze_coordinates") for det in record.get("gaze_detections", {}).values())
        )
        total_person_descriptions = sum(len(record.get("gaze_detections", {})) for record in sample_records)
        persons_with_detections = sum(
            1
            for record in sample_records
            for det in record.get("gaze_detections", {}).values()
            if det.get("gaze_coordinates")
        )

        for person in person_records:
            l2_error = person.get("gaze_l2_error")
            normalized_error = person.get("gaze_normalized_l2_error")
            angular_error = person.get("gaze_angular_error")
            iou_error = person.get("gaze_iou")
            modified_l2_error = person.get("gaze_modified_l2_error")
            if l2_error is not None:
                gaze_l2_errors.append(l2_error)
            if normalized_error is not None:
                gaze_normalized_l2_errors.append(normalized_error)
            if angular_error is not None:
                gaze_angular_errors.append(angular_error)
            if iou_error is not None:
                gaze_ious.append(iou_error)
            if modified_l2_error is not None:
                gaze_modified_l2_errors.append(modified_l2_error)

        for record in sample_records:
            pred_in_out = record.get("predicted_in_out")
            if pred_in_out is None:
                if config.in_out_labels_csv:
                    missing_in_out.add(str(record.get("id")))
                continue
            normalized_pred = 1 if int(pred_in_out) >= 1 else 0
            in_out_counts[normalized_pred] = in_out_counts.get(normalized_pred, 0) + 1

    restore_resume_state()

    def maybe_save_intermediate() -> None:
        if config.save_every <= 0:
            return
        processed = processed_count()
        if processed == 0 or processed % config.save_every != 0:
            return
        checkpoint_path = persist_intermediate_results(
            config=config,
            sample_records=sample_records,
            person_records=person_records,
            failed_samples=failed_samples,
            processed_samples=processed,
            dataset_gt_updates=dataset_gt_updates,
            dataset_updated=dataset_updated,
        )
        print(f"Saved intermediate results after {processed} samples to {checkpoint_path}")

    start_time = time.time()

    for sample in tqdm(dataset, desc="Evaluating dataset with Qwen3-VL"):
        sample_id = sample.get("id")
        image_value = sample.get("image", "")
        if "image" not in sample and "image_path" in sample:
            image_value = sample.get("image_path", "")
            image_value = "/".join(image_value.split("/")[-3:])
        conversations = sample.get("conversations", [])
        if not conversations and "model_prediction" in sample:
            ground_truth_text = sample.get("model_prediction", "")
        else:
            ground_truth_text = extract_ground_truth(conversations)
            
        if not ground_truth_text and not config.use_gpt_gaze_targets:
            failure_record: FailureRecord = {
                "id": sample_id,
                "reason": "Missing ground truth text",
                "image": image_value,
            }
            failed_samples.append(failure_record)
            maybe_save_intermediate()
            continue

        samples_with_ground_truth += 1

        image_path = resolve_image_path(image_value, images_dir)
        if image_path is None:
            failure_record: FailureRecord = {
                "id": sample_id,
                "reason": f"Image not found for '{image_value}'",
                "image": image_value,
            }
            failed_samples.append(failure_record)
            maybe_save_intermediate()
            continue

        image = load_image_rgb(image_path)
        width, height = image.size

        if image_path.is_relative_to(images_dir):
            relative_image_path = str(image_path.relative_to(images_dir))
        else:
            relative_image_path = str(image_path)
        relative_image_path = relative_image_path.replace("\\", "/")

        ground_truth_gaze = None
        gt_updated = False
        for mapping_ref in gt_caches:
            ground_truth_gaze, gt_updated = ensure_ground_truth_gaze(
                sample,
                relative_image_path,
                width,
                height,
                mapping_ref,
            )
            if ground_truth_gaze is not None:
                break
        if ground_truth_gaze is None:
            failure_record: FailureRecord = {
                "id": sample_id,
                "reason": "Ground-truth gaze unavailable",
                "image": image_value,
            }
            failed_samples.append(failure_record)
            close_image(image)
            maybe_save_intermediate()
            continue

        if gt_updated and ground_truth_gaze:
            dataset_updated = True
            update_record: DatasetUpdateRecord = {
                "id": sample.get("id"),
                "image": sample.get("image"),
                "relative_path": relative_image_path,
                "values": {
                    "gaze_gt_x": float(ground_truth_gaze[0]),
                    "gaze_gt_y": float(ground_truth_gaze[1]),
                    "gaze_gt_width": float(ground_truth_gaze[2]),
                    "gaze_gt_height": float(ground_truth_gaze[3]),
                },
            }
            dataset_gt_updates.append(update_record)

        gt_x, gt_y, gt_width, gt_height = ground_truth_gaze
        ground_truth_point = (gt_x, gt_y)

        if config.use_gpt_gaze_targets:
            gaze_descriptions = sample.get("extracted_gaze")
            gpt_gaze_target = gaze_descriptions.get("gaze_target", "")
            gpt_person_description = gaze_descriptions.get("person_description", "")

            persons: List[PersonDescription] = [
                PersonDescription(
                    person_id="person_1",
                    label="Person 1",
                    raw_description=gpt_person_description,
                    gaze_target=gpt_gaze_target,
                )
            ]
        else:
            persons = parse_person_descriptions(ground_truth_text)
            if not persons and ground_truth_text:
                persons = parse_person_descriptions(f"Person 1: {ground_truth_text}")

            if not persons:
                failure_record: FailureRecord = {
                    "id": sample_id,
                    "reason": "Could not parse person descriptions",
                    "image": image_value,
                }
                failed_samples.append(failure_record)
                close_image(image)
                maybe_save_intermediate()
                continue

        samples_with_person_descriptions += 1
        total_person_descriptions += len(persons)

        gt_in_out_value = resolve_in_out_label(sample, in_out_lookup, persons)
        pred_in_out_value = resolve_in_out_label(
            sample=sample,
            lookup={},
            descriptions=persons,
            use_model_prediction_offcamera=config.use_gpt_gaze_targets,
        )
        if gt_in_out_value == -1 or pred_in_out_value == -1:
            skipped_in_out_minus_one.add(str(sample_id))
            close_image(image)
            maybe_save_intermediate()
            continue
        pred_in_out_value = 0 if pred_in_out_value is None else pred_in_out_value
        if pred_in_out_value is not None:
            in_out_counts[pred_in_out_value] = in_out_counts.get(pred_in_out_value, 0) + 1
        elif config.in_out_labels_csv or sample.get("in_out") is not None:
            missing_in_out.add(str(sample_id))

        sample_entry: Dict[str, Any] = {
            "id": sample_id,
            "image_path": str(image_path),
            "dataset_prompt": extract_prompt(conversations),
            "ground_truth": ground_truth_text,
            "gaze_ground_truth": {
                "x": gt_x,
                "y": gt_y,
                "image_width": gt_width,
                "image_height": gt_height,
            },
            "gaze_detections": {},
        }

        any_detection_for_sample = False

        for person in persons:
            sanitized_description = normalize_person_description(person.raw_description)
            gaze_target_text = normalize_gaze_target_text(person.gaze_target)

            predicted_box: Optional[List[int]] = None
            gaze_score: Optional[float] = None
            errors = compute_gaze_errors(
                predicted_box=None,
                person_box=None,
                ground_truth_point=ground_truth_point,
                image_width=gt_width,
                image_height=gt_height,
                iou_radius_ratio=config.gaze_iou_radius_ratio,
            )

            if gaze_target_text and gt_in_out_value == 1:
                query = build_qwen_query(gaze_target_text)
                try:
                    detections, _ = run_qwen3vl_grounding(
                        image_path=str(image_path),
                        query=query,
                        model_id=config.gaze_model_id,
                        max_new_tokens=config.max_new_tokens,
                        processor=qwen_processor,
                        model=qwen_model,
                        device_map=device_map,
                        temperature=0.0,
                    )
                except Exception as exc:  # noqa: BLE001 - surface model decoding errors
                    detections = []
                    print(f"[Warning] Qwen3-VL failed on sample '{sample_id}' ({person.person_id}): {exc}")

                best_detection, best_errors = choose_best_detection_by_error(
                    detections=detections,
                    ground_truth_point=ground_truth_point,
                    image_width=gt_width,
                    image_height=gt_height,
                    score_threshold=config.gaze_box_threshold,
                    iou_radius_ratio=config.gaze_iou_radius_ratio,
                )

                if best_detection is not None:
                    predicted_box = extract_bbox(best_detection)
                    gaze_score = extract_score(best_detection)
                    if best_errors is not None:
                        errors = best_errors
                else:
                    pred_in_out_value = 0  # No detection implies "out of frame"

            if pred_in_out_value is not None:
                sample_entry["predicted_in_out"] = pred_in_out_value
            if gt_in_out_value is not None:
                sample_entry["gt_in_out"] = gt_in_out_value

            record = {
                "label": person.label,
                "person_description": sanitized_description,
                "gaze_target": gaze_target_text,
                "gaze_coordinates": predicted_box,
                "gaze_score": gaze_score,
                "person_coordinates": None,
                "person_score": None,
                "gaze_ground_truth": {"x": gt_x, "y": gt_y},
                **errors,
            }

            if predicted_box:
                persons_with_detections += 1
                any_detection_for_sample = True

            l2_error = errors.get("gaze_l2_error")
            normalized_error = errors.get("gaze_normalized_l2_error")
            angular_error = errors.get("gaze_angular_error")
            iou = errors.get("gaze_iou")
            modified_l2_error = errors.get("gaze_modified_l2_error")

            if l2_error is not None:
                gaze_l2_errors.append(l2_error)
            if normalized_error is not None:
                gaze_normalized_l2_errors.append(normalized_error)
            if angular_error is not None:
                gaze_angular_errors.append(angular_error)
            if iou is not None:
                gaze_ious.append(iou)
            if modified_l2_error is not None:
                gaze_modified_l2_errors.append(modified_l2_error)

            sample_entry["gaze_detections"][person.person_id] = record
            person_record: PersonLevelRecord = {
                "sample_id": sample_id,
                "person_id": person.person_id,
                "person_description": sanitized_description,
                "gaze_target": gaze_target_text,
                "gaze_score": gaze_score,
                "person_score": None,
                "gaze_l2_error": l2_error,
                "gaze_normalized_l2_error": normalized_error,
                "gaze_angular_error": angular_error,
                "gaze_iou": iou,
                "gaze_modified_l2_error": modified_l2_error,
            }
            person_records.append(person_record)

        if any_detection_for_sample:
            samples_with_detections += 1

        sample_records.append(sample_entry)
        close_image(image)
        maybe_save_intermediate()

    duration = time.time() - start_time
    processed_total = processed_count()
    reported_total = max(total_samples, processed_total)

    metrics: Dict[str, Any] = {
        "total_samples": reported_total,
        "samples_with_ground_truth": samples_with_ground_truth,
        "samples_with_person_descriptions": samples_with_person_descriptions,
        "samples_with_gaze_detections": samples_with_detections,
        "total_person_descriptions": total_person_descriptions,
        "persons_with_gaze_detections": persons_with_detections,
        "evaluation_time_seconds": duration,
        "average_time_per_sample": duration / reported_total if reported_total else 0.0,
        "failed_samples": len(failed_samples),
    }
    metrics["samples_with_in_out"] = in_out_counts[0] + in_out_counts[1]
    metrics["in_out_in_frame"] = in_out_counts[1]
    metrics["in_out_out_of_frame"] = in_out_counts[0]
    metrics["missing_in_out"] = len(missing_in_out)
    metrics["skipped_in_out_minus_one"] = len(skipped_in_out_minus_one)

    if gaze_l2_errors:
        metrics["gaze_l2_error_mean"] = sum(gaze_l2_errors) / len(gaze_l2_errors)
        metrics["gaze_l2_error_median"] = statistics.median(gaze_l2_errors)
        metrics["gaze_l2_error_count"] = len(gaze_l2_errors)
    if gaze_normalized_l2_errors:
        metrics["gaze_l2_normalized_mean"] = sum(gaze_normalized_l2_errors) / len(gaze_normalized_l2_errors)
        metrics["gaze_l2_normalized_median"] = statistics.median(gaze_normalized_l2_errors)
        metrics["gaze_l2_normalized_count"] = len(gaze_normalized_l2_errors)
    if gaze_angular_errors:
        metrics["gaze_angular_error_mean"] = sum(gaze_angular_errors) / len(gaze_angular_errors)
        metrics["gaze_angular_error_median"] = statistics.median(gaze_angular_errors)
        metrics["gaze_angular_error_count"] = len(gaze_angular_errors)
    if gaze_ious:
        metrics["gaze_iou_mean"] = sum(gaze_ious) / len(gaze_ious)
        metrics["gaze_iou_median"] = statistics.median(gaze_ious)
        metrics["gaze_iou_count"] = len(gaze_ious)
    if gaze_modified_l2_errors:
        metrics["gaze_modified_l2_error_mean"] = sum(gaze_modified_l2_errors) / len(gaze_modified_l2_errors)
        metrics["gaze_modified_l2_error_median"] = statistics.median(gaze_modified_l2_errors)
        metrics["gaze_modified_l2_error_count"] = len(gaze_modified_l2_errors)

    return EvaluationResults(
        metrics=metrics,
        sample_records=sample_records,
        person_records=person_records,
        failed_samples=failed_samples,
        dataset_gt_updates=dataset_gt_updates,
        dataset_updated=dataset_updated,
    )


def main() -> None:
    args = parse_args()
    config = EvaluationConfig.from_args(args)
    config.output_dir.mkdir(parents=True, exist_ok=True)

    results = evaluate_dataset(config)
    paths = persist_evaluation_results(config, results)
    log_results_to_wandb(config, results, paths)
    print_metrics(results.metrics)


if __name__ == "__main__":
    main()
