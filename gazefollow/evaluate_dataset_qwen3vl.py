#!/usr/bin/env python3
"""
Evaluate gaze annotations in a dataset by running Qwen3-VL grounding on the
ground-truth descriptions. The script reuses the text prompts that were
provided as ground truth answers, extracts the referenced gaze targets,
performs localization using the Qwen3-VL vision-language model, and reports the
same error metrics (L2, normalized L2, angular error) that are produced during
model evaluation.
"""

from __future__ import annotations

import argparse
import importlib
import json
import statistics
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from PIL import Image
from tqdm import tqdm

from gazefollow.auto_phrase_grounding.detect_gaze_targets import (
    normalize_gaze_target_text,
    normalize_person_description,
    parse_person_descriptions,
)
from gazefollow.auto_phrase_grounding.qwen3vl_grounding import (
    load_qwen3vl_model,
    run_qwen3vl_grounding,
)
from gazefollow.gaze_metrics import (
    compute_gaze_errors,
    ensure_ground_truth_gaze,
    load_combined_description_cache,
    persist_ground_truth_updates,
)


def load_image_rgb(path: Path) -> Image.Image:
    image = Image.open(path)
    if image.mode == "RGB":
        return image
    converted = image.convert("RGB")
    image.close()
    return converted


def close_image(image: Optional[Image.Image]) -> None:
    if image is not None:
        image.close()


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Evaluate dataset gaze annotations using Qwen3-VL on ground-truth descriptions."
    )
    parser.add_argument("--dataset-json", required=True, help="Path to the dataset JSON file.")
    parser.add_argument("--images-dir", required=True, help="Directory containing dataset images.")
    parser.add_argument(
        "--output-dir",
        default="./dataset_evaluation_results",
        help="Directory where evaluation artifacts will be stored.",
    )
    parser.add_argument("--limit", type=int, default=None, help="Limit number of samples to process.")
    parser.add_argument(
        "--gaze-model-id",
        default="Qwen/Qwen3-VL-4B-Instruct",
        help="Qwen3-VL model identifier to use.",
    )
    parser.add_argument(
        "--gaze-box-threshold",
        type=float,
        default=0.20,
        help="Minimum confidence score accepted for detections (if provided by the model).",
    )
    parser.add_argument(
        "--gaze-text-threshold",
        type=float,
        default=0.20,
        help="Unused placeholder to keep parity with the GroundingDINO evaluator.",
    )
    parser.add_argument(
        "--gaze-device",
        type=str,
        default=None,
        help="Optional device map passed to the Qwen3-VL loader (e.g., 'cuda:0').",
    )
    parser.add_argument(
        "--max-new-tokens",
        type=int,
        default=300,
        help="Maximum number of tokens generated by Qwen3-VL.",
    )
    parser.add_argument(
        "--save-records",
        action="store_true",
        help="Persist per-sample localization results to JSON.",
    )
    parser.add_argument(
        "--no-save-records",
        dest="save_records",
        action="store_false",
        help="Disable saving per-sample localization results.",
    )
    parser.set_defaults(save_records=True)
    parser.add_argument(
        "--log-to-wandb",
        dest="log_to_wandb",
        action="store_true",
        help="Enable wandb logging (default).",
    )
    parser.add_argument(
        "--no-log-to-wandb",
        dest="log_to_wandb",
        action="store_false",
        help="Disable wandb logging.",
    )
    parser.set_defaults(log_to_wandb=True)
    parser.add_argument("--wandb-project", default="llava-dataset-eval", help="wandb project name.")
    parser.add_argument("--wandb-entity", default=None, help="wandb entity (team) name.")
    parser.add_argument(
        "--wandb-run-name",
        default=None,
        help="Explicit wandb run name. Defaults to an auto-generated name.",
    )
    parser.add_argument(
        "--wandb-run-name-suffix",
        default="",
        help="Suffix appended to the auto-generated wandb run name.",
    )
    return parser.parse_args()


def load_dataset(json_path: str, limit: Optional[int]) -> List[Dict[str, Any]]:
    dataset_path = Path(json_path)
    if not dataset_path.exists():
        raise FileNotFoundError(f"Dataset JSON not found: {json_path}")

    with dataset_path.open("r", encoding="utf-8") as dataset_file:
        data = json.load(dataset_file)

    if not isinstance(data, list):
        raise ValueError("Dataset JSON must contain a list of samples.")

    if limit is not None:
        data = data[:limit]
    return data


def extract_prompt(conversations: List[Dict[str, str]]) -> str:
    for turn in conversations:
        if turn.get("from") == "human":
            return turn.get("value", "").replace("<image>", "").strip()
    return ""


def extract_ground_truth(conversations: List[Dict[str, str]]) -> str:
    for turn in conversations:
        if turn.get("from") == "gpt":
            return turn.get("value", "").strip()
    return ""


def resolve_image_path(image_value: str, images_dir: Path) -> Optional[Path]:
    if not image_value:
        return None
    candidate = images_dir / image_value
    if candidate.exists():
        return candidate
    if candidate.suffix:
        return None
    for ext in (".jpg", ".png", ".jpeg"):
        alt = candidate.with_suffix(ext)
        if alt.exists():
            return alt
    return None


def build_qwen_query(
    person_label: str,
    person_description: str,
    gaze_target: str,
    person_id: str,
) -> str:
    normalized_description = person_description or person_label
    gaze_json = json.dumps(gaze_target)
    person_id_json = json.dumps(person_id)
    return (
        "Locate the gaze target for the described person. "
        "Return a JSON array with a single object following the schema: "
        f"[{{\"person_id\": {person_id_json}, \"label\": {gaze_json}, \"bbox\": [x1, y1, x2, y2], \"score\": confidence}}]]. "
        "Use integers between 0 and 1000 for bbox coordinates representing the top-left and bottom-right corners. "
        "Person description: "
        f"{normalized_description}. "
        "Gaze target phrase: "
        f"{gaze_target}."
    )


def extract_bbox(detection: Dict[str, Any]) -> Optional[List[int]]:
    for key, value in detection.items():
        if not isinstance(key, str):
            continue
        if "bbox" not in key.lower():
            continue
        if isinstance(value, Sequence) and len(value) == 4:
            try:
                return [int(float(coord)) for coord in value]
            except (TypeError, ValueError):
                return None
    return None


def extract_score(detection: Dict[str, Any]) -> Optional[float]:
    for key in ("score", "confidence", "prob", "probability"):
        value = detection.get(key)
        if isinstance(value, (int, float)):
            return float(value)
    return None


def choose_detection(
    detections: List[Dict[str, Any]],
    score_threshold: float,
) -> Optional[Dict[str, Any]]:
    selected: Optional[Dict[str, Any]] = None
    selected_score: Optional[float] = None
    for detection in detections:
        bbox = extract_bbox(detection)
        if not bbox:
            continue
        score = extract_score(detection)
        if score is not None and score < score_threshold:
            continue
        if selected is None:
            selected = detection
            selected_score = score
            continue
        if score is not None and (selected_score is None or score > selected_score):
            selected = detection
            selected_score = score
    return selected


def create_wandb_run(args: argparse.Namespace, metrics: Dict[str, Any]) -> Optional[Any]:
    if not args.log_to_wandb:
        return None

    wandb_spec = importlib.util.find_spec("wandb")
    if wandb_spec is None:
        print("Warning: wandb is not available. Disable logging with --no-log-to-wandb to silence this message.")
        return None

    wandb = importlib.import_module("wandb")
    dataset_stem = Path(args.dataset_json).stem
    model_stem = args.gaze_model_id.split("/")[-1]
    timestamp = time.strftime("%Y%m%d_%H%M%S")
    if args.wandb_run_name:
        run_name = args.wandb_run_name
    else:
        run_name = f"dataset-eval-{dataset_stem}-{model_stem}-{timestamp}"
        if args.wandb_run_name_suffix:
            run_name = f"{run_name}-{args.wandb_run_name_suffix}"

    config = {
        "dataset_json": args.dataset_json,
        "images_dir": args.images_dir,
        "gaze_model_id": args.gaze_model_id,
        "gaze_box_threshold": args.gaze_box_threshold,
        "max_new_tokens": args.max_new_tokens,
        "limit": args.limit,
        "device_map": args.gaze_device or "auto",
    }
    config.update({f"default_metrics/{k}": v for k, v in metrics.items() if isinstance(v, (int, float))})

    entity = args.wandb_entity
    project = args.wandb_project or "llava-dataset-eval"
    wandb_run = wandb.init(project=project, entity=entity, name=run_name, config=config, reinit=True)
    print(f"Initialized wandb run: {wandb_run.name}")
    return wandb_run


def main() -> None:
    args = parse_args()

    start_time = time.time()
    dataset = load_dataset(args.dataset_json, args.limit)
    images_dir = Path(args.images_dir)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    device_map = args.gaze_device or "auto"
    print(f"Loading Qwen3-VL model '{args.gaze_model_id}' with device map '{device_map}'...")
    qwen_processor, qwen_model = load_qwen3vl_model(args.gaze_model_id, device_map=device_map)

    combined_cache = load_combined_description_cache()

    sample_records: List[Dict[str, Any]] = []
    person_records: List[Dict[str, Any]] = []
    failed_samples: List[Dict[str, Any]] = []
    dataset_gt_updates: List[Dict[str, Any]] = []
    dataset_updated = False

    gaze_l2_errors: List[float] = []
    gaze_normalized_l2_errors: List[float] = []
    gaze_angular_errors: List[float] = []

    total_samples = len(dataset)
    samples_with_ground_truth = 0
    samples_with_person_descriptions = 0
    samples_with_detections = 0
    total_person_descriptions = 0
    persons_with_detections = 0

    for sample in tqdm(dataset, desc="Evaluating dataset with Qwen3-VL"):
        sample_id = sample.get("id")
        image_value = sample.get("image", "")
        conversations = sample.get("conversations", [])

        ground_truth_text = extract_ground_truth(conversations)
        if not ground_truth_text:
            failed_samples.append(
                {"id": sample_id, "reason": "Missing ground truth text", "image": image_value}
            )
            continue

        samples_with_ground_truth += 1

        image_path = resolve_image_path(image_value, images_dir)
        if image_path is None:
            failed_samples.append(
                {"id": sample_id, "reason": f"Image not found for '{image_value}'", "image": image_value}
            )
            continue

        image = load_image_rgb(image_path)
        width, height = image.size

        if image_path.is_relative_to(images_dir):
            relative_image_path = str(image_path.relative_to(images_dir))
        else:
            relative_image_path = str(image_path)
        relative_image_path = relative_image_path.replace("\\", "/")

        mapping_ref = combined_cache if combined_cache is not None else {}
        ground_truth_gaze, gt_updated = ensure_ground_truth_gaze(
            sample,
            relative_image_path,
            width,
            height,
            mapping_ref,
        )
        if ground_truth_gaze is None and combined_cache is None:
            combined_cache = load_combined_description_cache()
            mapping_ref = combined_cache
            ground_truth_gaze, gt_updated = ensure_ground_truth_gaze(
                sample,
                relative_image_path,
                width,
                height,
                mapping_ref,
            )
        if ground_truth_gaze is None:
            failed_samples.append(
                {"id": sample_id, "reason": "Ground-truth gaze unavailable", "image": image_value}
            )
            close_image(image)
            continue

        if gt_updated and ground_truth_gaze:
            dataset_updated = True
            dataset_gt_updates.append(
                {
                    "id": sample.get("id"),
                    "image": sample.get("image"),
                    "relative_path": relative_image_path,
                    "values": {
                        "gaze_gt_x": ground_truth_gaze[0],
                        "gaze_gt_y": ground_truth_gaze[1],
                        "gaze_gt_width": ground_truth_gaze[2],
                        "gaze_gt_height": ground_truth_gaze[3],
                    },
                }
            )

        gt_x, gt_y, gt_width, gt_height = ground_truth_gaze
        ground_truth_point = (gt_x, gt_y)

        persons = parse_person_descriptions(ground_truth_text)
        if not persons and ground_truth_text:
            persons = parse_person_descriptions(f"Person 1: {ground_truth_text}")

        if not persons:
            failed_samples.append(
                {"id": sample_id, "reason": "Could not parse person descriptions", "image": image_value}
            )
            close_image(image)
            continue

        samples_with_person_descriptions += 1
        total_person_descriptions += len(persons)

        sample_entry: Dict[str, Any] = {
            "id": sample_id,
            "image_path": str(image_path),
            "dataset_prompt": extract_prompt(conversations),
            "ground_truth": ground_truth_text,
            "gaze_ground_truth": {
                "x": gt_x,
                "y": gt_y,
                "image_width": gt_width,
                "image_height": gt_height,
            },
            "gaze_detections": {},
        }

        any_detection_for_sample = False

        for person in persons:
            sanitized_description = normalize_person_description(person.raw_description)
            gaze_target_text = normalize_gaze_target_text(person.gaze_target)

            predicted_box: Optional[List[int]] = None
            gaze_score: Optional[float] = None

            if gaze_target_text:
                query = build_qwen_query(person.label, sanitized_description or person.raw_description, gaze_target_text, person.person_id)
                try:
                    detections = run_qwen3vl_grounding(
                        image_path=str(image_path),
                        query=query,
                        model_id=args.gaze_model_id,
                        max_new_tokens=args.max_new_tokens,
                        processor=qwen_processor,
                        model=qwen_model,
                        device_map=device_map,
                    )
                except Exception as exc:  # noqa: BLE001 - surface model decoding errors
                    detections = []
                    print(f"[Warning] Qwen3-VL failed on sample '{sample_id}' ({person.person_id}): {exc}")
                chosen = choose_detection(detections, args.gaze_box_threshold)
                if chosen is not None:
                    predicted_box = extract_bbox(chosen)
                    gaze_score = extract_score(chosen)

            errors = compute_gaze_errors(
                predicted_box=predicted_box,
                person_box=None,
                ground_truth_point=ground_truth_point,
                image_width=gt_width,
                image_height=gt_height,
            )

            record = {
                "label": person.label,
                "person_description": sanitized_description,
                "gaze_target": gaze_target_text,
                "gaze_coordinates": predicted_box,
                "gaze_score": gaze_score,
                "person_coordinates": None,
                "person_score": None,
                "gaze_ground_truth": {"x": gt_x, "y": gt_y},
                **errors,
            }

            if predicted_box:
                persons_with_detections += 1
                any_detection_for_sample = True

            l2_error = errors.get("gaze_l2_error")
            normalized_error = errors.get("gaze_normalized_l2_error")
            angular_error = errors.get("gaze_angular_error")

            if l2_error is not None:
                gaze_l2_errors.append(l2_error)
            if normalized_error is not None:
                gaze_normalized_l2_errors.append(normalized_error)
            if angular_error is not None:
                gaze_angular_errors.append(angular_error)

            sample_entry["gaze_detections"][person.person_id] = record
            person_records.append(
                {
                    "sample_id": sample_id,
                    "person_id": person.person_id,
                    "person_description": sanitized_description,
                    "gaze_target": gaze_target_text,
                    "gaze_score": gaze_score,
                    "person_score": None,
                    "gaze_l2_error": l2_error,
                    "gaze_normalized_l2_error": normalized_error,
                    "gaze_angular_error": angular_error,
                }
            )

        if any_detection_for_sample:
            samples_with_detections += 1

        sample_records.append(sample_entry)
        close_image(image)

    if dataset_updated and dataset_gt_updates:
        persisted = persist_ground_truth_updates(Path(args.dataset_json), dataset_gt_updates)
        if persisted:
            print(f"Persisted gaze ground truth for {persisted} samples to {args.dataset_json}")

    duration = time.time() - start_time

    metrics: Dict[str, Any] = {
        "total_samples": total_samples,
        "samples_with_ground_truth": samples_with_ground_truth,
        "samples_with_person_descriptions": samples_with_person_descriptions,
        "samples_with_gaze_detections": samples_with_detections,
        "total_person_descriptions": total_person_descriptions,
        "persons_with_gaze_detections": persons_with_detections,
        "evaluation_time_seconds": duration,
        "average_time_per_sample": duration / total_samples if total_samples else 0.0,
        "failed_samples": len(failed_samples),
    }

    if gaze_l2_errors:
        metrics["gaze_l2_error_mean"] = sum(gaze_l2_errors) / len(gaze_l2_errors)
        metrics["gaze_l2_error_median"] = statistics.median(gaze_l2_errors)
        metrics["gaze_l2_error_count"] = len(gaze_l2_errors)
    if gaze_normalized_l2_errors:
        metrics["gaze_l2_normalized_mean"] = sum(gaze_normalized_l2_errors) / len(gaze_normalized_l2_errors)
        metrics["gaze_l2_normalized_median"] = statistics.median(gaze_normalized_l2_errors)
        metrics["gaze_l2_normalized_count"] = len(gaze_normalized_l2_errors)
    if gaze_angular_errors:
        metrics["gaze_angular_error_mean"] = sum(gaze_angular_errors) / len(gaze_angular_errors)
        metrics["gaze_angular_error_median"] = statistics.median(gaze_angular_errors)
        metrics["gaze_angular_error_count"] = len(gaze_angular_errors)

    metrics_path = output_dir / "metrics.json"
    with metrics_path.open("w", encoding="utf-8") as metrics_file:
        json.dump(metrics, metrics_file, indent=2, ensure_ascii=False)

    records_path: Optional[Path] = None
    person_path: Optional[Path] = None
    failed_path: Optional[Path] = None

    if args.save_records:
        records_path = output_dir / "dataset_localization_results.json"
        with records_path.open("w", encoding="utf-8") as results_file:
            json.dump(sample_records, results_file, indent=2, ensure_ascii=False)

        person_path = output_dir / "person_level_results.json"
        with person_path.open("w", encoding="utf-8") as person_file:
            json.dump(person_records, person_file, indent=2, ensure_ascii=False)

    if failed_samples:
        failed_path = output_dir / "failures.json"
        with failed_path.open("w", encoding="utf-8") as failed_file:
            json.dump(failed_samples, failed_file, indent=2, ensure_ascii=False)

    wandb_run = create_wandb_run(args, metrics)
    if wandb_run is not None:
        wandb = importlib.import_module("wandb")
        wandb_metrics = {f"dataset_eval/{k}": v for k, v in metrics.items() if isinstance(v, (int, float))}
        wandb.log(wandb_metrics)

        if person_records:
            table = wandb.Table(
                columns=[
                    "sample_id",
                    "person_id",
                    "person_description",
                    "gaze_target",
                    "gaze_score",
                    "person_score",
                    "gaze_l2_error",
                    "gaze_normalized_l2_error",
                    "gaze_angular_error",
                ]
            )
            for record in person_records:
                table.add_data(
                    record.get("sample_id"),
                    record.get("person_id"),
                    record.get("person_description"),
                    record.get("gaze_target"),
                    record.get("gaze_score"),
                    record.get("person_score"),
                    record.get("gaze_l2_error"),
                    record.get("gaze_normalized_l2_error"),
                    record.get("gaze_angular_error"),
                )
            wandb.log({"dataset_eval/person_localization": table})

        artifact = wandb.Artifact(
            name=f"dataset_evaluation_{wandb_run.id}",
            type="dataset-evaluation",
            description="Ground-truth localization evaluation artifacts (Qwen3-VL).",
        )
        artifact.add_file(str(metrics_path), name="metrics.json")
        if args.save_records and records_path and person_path:
            artifact.add_file(str(records_path), name="dataset_localization_results.json")
            artifact.add_file(str(person_path), name="person_level_results.json")
        if failed_samples and failed_path:
            artifact.add_file(str(failed_path), name="failures.json")
        wandb.log_artifact(artifact)
        wandb.finish()

    print("\nEvaluation complete. Metrics:")
    for key, value in metrics.items():
        if isinstance(value, float):
            print(f"  {key}: {value:.4f}")
        else:
            print(f"  {key}: {value}")


if __name__ == "__main__":
    main()
